#!/usr/bin/env python3
"""gen_bench_data.py - writes bench_data.asm for TFT4_Bench from the scene
definitions of the emulator suite (FR6989_Invaders_dev/bench_tft4_vs_ti/suite.py),
so the hardware bench and the emulator run exactly the same scenes.

  python3 tools/gen_bench_data.py <path to suite.py dir> [bench_data.asm] [bench_data.h]

The .h file is the same data for the C benchmark (TI_C_Bench, TI's driver).
"""
import os, sys
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else '.')
import suite

OUT = sys.argv[2] if len(sys.argv) > 2 else 'bench_data.asm'
KIND = {'idle': 0, 'movers': 1, 'hud': 2, 'pixels': 3, 'fill': 4, 'stripes': 5, 'palette': 6}
NAMES = ['Idle', '1 ball 8x8', '4 balls 8x8', '16 balls 8x8', '32 balls 8x8', '1 ball 16x16',
         '1 ball 32x32', '1 ball 64x64', '8 overlap 16', 'HUD counter', '64 pixels', 'Full fill',
         'Stripes', 'Palette']
SPR_LABEL = {'b8': 'Ball8', 'b16': 'Ball16', 'b32': 'Ball32', 'b64': 'Ball64'}

L = [";******************************************************************************",
     "; bench_data.asm - GENERATED by tools/gen_bench_data.py from suite.py, don't edit",
     "; Scenes, sprites and background of the tft4 benchmark (the same ones the",
     "; emulator suite runs, so hardware and emulator numbers can be compared).",
     ";******************************************************************************",
     "\t.def    SceneTable, SceneCount, BgOps, DigTab, PalAnim",
     "", "\t.sect   \".const\"", ""]


def sprite(label, rows):
    w, h = len(rows[0]), len(rows)
    L.append(f"{label}\t.byte   {w}, {h}")
    for row in rows:
        rr = row + [0] * (w % 2)
        L.append("\t.byte   " + ", ".join(f"0x{(rr[i] << 4) | rr[i + 1]:02X}" for i in range(0, len(rr), 2)))
    L.append("\t.align  2")


def text(label, t):
    assert len(t) <= 12
    L.append(f"{label}\t.byte   " + ", ".join(str(ord(c)) for c in t) + f", 0\t; \"{t}\"")


# background: sky, 24 stars, ground, grass (x, y, w + h << 8, color), ends with 0xFFFF
L.append("; Background: x, y, w + (h << 8), color; 0xFFFF ends the list")
L.append("BgOps")
for (x, y, w, h, c) in suite.background_ops():
    L.append(f"\t.word   {x}, {y}, 0x{w | (h << 8):04X}, {c}")
L += ["\t.word   0xFFFF", ""]

# scenes
scenes = suite.scenes()
assert len(scenes) == len(NAMES)
L.append("SceneCount\t.word   %d" % len(scenes))
L.append("")
L.append("; Scene: kind, name, sprite, count, start table, x min, y min, x max, y max")
L.append("; kinds: 0 idle, 1 moving sprites, 2 HUD, 3 pixels, 4 fill, 5 stripes, 6 palette")
L.append("SceneTable")
inits = []
for i, ((title, kind, factory), name) in enumerate(zip(scenes, NAMES)):
    movers = factory() if factory else []
    k = 'idle' if kind == 'movers' and not movers else kind
    if movers:
        m = movers[0]
        assert len(movers) == 1
        bx, by, bw, bh = m.box
        init = f"Start{i}"
        inits.append((init, m.p))
        L.append(f"\t.word   {KIND[k]}, Name{i}, {SPR_LABEL[m.name]}, {len(m.p)}, {init}, "
                 f"{bx}, {by}, {bx + bw - m.w}, {by + bh - m.h}\t; {title}")
    else:
        L.append(f"\t.word   {KIND[k]}, Name{i}, 0, 0, 0, 0, 0, 0, 0\t; {title}")
L.append("")
L.append("; Start positions and speeds of the moving sprites: x, y, dx, dy")
for (label, p) in inits:
    L.append(label)
    for (x, y, dx, dy) in p:
        L.append(f"\t.word   {x}, {y}, {dx}, {dy}")
L.append("")
for i, name in enumerate(NAMES):
    text(f"Name{i}", name)
L.append("\t.align  2")
L.append("")
L.append("; Palette animation: sky color per frame (f % 4), RGB565")
L.append("PalAnim\t.word   " + ", ".join(f"0x{suite.rgb565(c):04X}" for c in (0x1D2B53, 0x2B3B73, 0x3B4B93, 0x4B5BB3)))
L.append("")
L.append("; Sprites (see tft4.asm for the format)")
for k, lab in SPR_LABEL.items():
    sprite(lab, suite.ART[k])
L.append("; HUD digits 6x10, opaque")
L.append("DigTab\t.word   " + ", ".join(f"Dig{d}" for d in range(10)))
for d in range(10):
    sprite(f"Dig{d}", suite.ART[f'd{d}'])
L.append("\t.end")
open(OUT, 'w').write("\n".join(L) + "\n")
print("wrote", OUT)

# ---------------------------------------------------------------- C header
if len(sys.argv) > 3:
    C = ["/* bench_data.h - GENERATED by tools/gen_bench_data.py from suite.py, don't edit.",
         " * Scenes, images and background of the benchmark, the same ones TFT4_Bench and",
         " * the emulator suite use. Include it in one .c file only. */",
         "#ifndef BENCH_DATA_H", "#define BENCH_DATA_H", '#include "grlib.h"', "",
         "enum { K_IDLE, K_MOVERS, K_HUD, K_PIXELS, K_FILL, K_STRIPES, K_PALETTE };",
         "typedef struct { int16_t x, y, dx, dy; } Start;",
         "typedef struct { uint8_t kind; const char *name; const Graphics_Image *img; uint8_t count;",
         "                 const Start *start; int16_t xmin, ymin, xmax, ymax; } Scene;", "",
         "/* palette as 24-bit colors; the palette scene changes entry 1 (sky) */",
         "uint32_t kPal[16] = { " + ", ".join(f"0x{c:06X}" for c in suite.PAL) + " };",
         "#define SKY_RGB 0x%06X" % suite.PAL[1],
         "static const uint32_t kPalAnim[4] = { 0x1D2B53, 0x2B3B73, 0x3B4B93, 0x4B5BB3 };", ""]
    C.append("/* background: x, y, w, h, color */")
    ops = suite.background_ops()
    C.append("#define BG_OPS %d" % len(ops))
    C.append("static const int16_t kBgOps[BG_OPS][5] = {")
    C += [f"    {{ {x}, {y}, {w}, {h}, {c} }}," for (x, y, w, h, c) in ops]
    C += ["};", ""]

    def cimg(label, rows):
        w, h = len(rows[0]), len(rows)
        data = []
        for row in rows:
            rr = row + [0] * (w % 2)
            data += [(rr[i] << 4) | rr[i + 1] for i in range(0, len(rr), 2)]
        C.append(f"static const uint8_t {label}Pix[{len(data)}] = {{")
        for i in range(0, len(data), 16):
            C.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
        C.append("};")
        C.append(f"static const Graphics_Image {label} = {{ IMAGE_FMT_4BPP_UNCOMP, {w}, {h}, 16, kPal, {label}Pix }};")

    for k, lab in SPR_LABEL.items():
        cimg(lab, suite.ART[k])
    for d in range(10):
        cimg(f"Dig{d}", suite.ART[f'd{d}'])
    C.append("static const Graphics_Image *const kDigits[10] = { " + ", ".join(f"&Dig{d}" for d in range(10)) + " };")
    C.append("")
    for i, ((title, kind, factory), name) in enumerate(zip(scenes, NAMES)):
        movers = factory() if factory else []
        if movers:
            C.append(f"static const Start kStart{i}[{len(movers[0].p)}] = {{")
            C += [f"    {{ {x}, {y}, {dx}, {dy} }}," for (x, y, dx, dy) in movers[0].p]
            C.append("};")
    C.append("")
    C.append("#define SCENE_COUNT %d" % len(scenes))
    C.append("static const Scene kScenes[SCENE_COUNT] = {")
    kn = ['K_IDLE', 'K_MOVERS', 'K_HUD', 'K_PIXELS', 'K_FILL', 'K_STRIPES', 'K_PALETTE']
    for i, ((title, kind, factory), name) in enumerate(zip(scenes, NAMES)):
        movers = factory() if factory else []
        k = 'idle' if kind == 'movers' and not movers else kind
        if movers:
            m = movers[0]
            bx, by, bw, bh = m.box
            C.append(f'    {{ {kn[KIND[k]]}, "{name}", &{SPR_LABEL[m.name]}, {len(m.p)}, kStart{i}, '
                     f'{bx}, {by}, {bx + bw - m.w}, {by + bh - m.h} }},  /* {title} */')
        else:
            C.append(f'    {{ {kn[KIND[k]]}, "{name}", 0, 0, 0, 0, 0, 0, 0 }},  /* {title} */')
    C += ["};", "", "#endif", ""]
    open(sys.argv[3], 'w').write("\n".join(C))
    print("wrote", sys.argv[3])
